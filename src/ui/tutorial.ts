// ⚠️ **type-only**（编译期擦除）：内容层不产生任何运行期依赖（"待消费意图"要靠它）
import type { WorkbenchContext } from '../core/context';

export interface TutorialArticle {
  id: string;
  /** 折叠卡上的标题 */
  title: string;
  /** 卡片头上的一行小字说明（可选） */
  sub?: string;
  /**
   * **配图**（P7.10 · #8）：`assets/tutorial/` 下的文件名（1–2 张）。帮助栏卡片在正文
   * **之前**把它们画出来（与向导同款的 `<img>` + 加载失败整块隐藏）。
   * 出片脚本 = `scripts/shoot-tutorial.mjs`（照 `shoot-wizard.mjs` 先例，只连演示库）。
   */
  shots?: string[];
  /**
   * Markdown 正文。首行**不写 H1**（标题就是卡头那一行，导出成笔记时文件名也是它）。
   */
  md: string;
}

// ────────────────────────────────────────────────────────────────
// 「落到某一篇」的待消费意图（P7.10 从 `ui/settings/help.ts` **原样搬来**）
// ────────────────────────────────────────────────────────────────
/**
 * 为什么不给 `openWorkbenchSettings` 加个 anchor 参数：面板的挂载/换栏是异步的一条链，
 * 参数得一路穿透三四个签名才能到那一栏；而"寄存意图 → 由目标栏自己消费"是本项目
 * 模块系统一直在用的形状。消费一次即清 —— 用户之后自己点开帮助栏时，不该再被自动展开一次。
 *
 * ⚠️ P7.10 搬家理由：`ui/new-note.ts` 也要用它（#7 的「如何新建模板」按钮），而
 * `help.ts` 反过来 import `new-note` 的 `openNewNoteDialog` —— 留在 help.ts 就是一个
 * **模块环**。这一份"意图寄存"与教程内容本来就近，搬进来两边都干净（内容层不 import ui）。
 */
let pendingArticle: string | null = null;

/** 打开设置面板并落到教程中心的某一篇（展开 + 滚到位）。`articleId` = 本文的 id */
export function openTutorialCenter(ctx: WorkbenchContext, articleId: string): void {
  pendingArticle = articleId;
  ctx.openWorkbenchSettings('help');
}

/** 帮助栏挂载时取走意图（**消费一次即清**） */
export function consumePendingArticle(): string | null {
  const p = pendingArticle;
  pendingArticle = null;
  return p;
}

